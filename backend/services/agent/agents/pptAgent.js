import PptxGenJS from 'pptxgenjs';
import { HumanMessage, SystemMessage } from "@langchain/core/messages";
import { getModel } from "../config/llmModels.js";
import { storeFileAndGetUrl } from "../utils/storageService.js";

/**
 * PPT Agent:
 * 1. LLM creates structured slide deck JSON (title, slides: [title, bullets, takeaway]).
 * 2. PptxGenJS compiles modern 16:9 widescreen PowerPoint presentation (.pptx).
 * 3. Saves via S3-ready storage abstraction and returns download URL.
 */
export const runPptAgent = async (prompt) => {
    const model = getModel('ppt');

    // 1. LLM structures slides in structured JSON
    const systemPrompt = new SystemMessage(
        `You are Cortex AI's Executive Presentation Designer.
Create a structured 4-to-6 slide presentation deck for the user's prompt.
You MUST output ONLY a valid JSON object matching this schema:
{
  "deckTitle": "Main Presentation Title",
  "subtitle": "Clear executive subtitle or target audience",
  "slides": [
    {
      "slideTitle": "Slide Title",
      "bulletPoints": [
        "First key insight with supporting detail",
        "Second actionable strategic point",
        "Third measurable metric or observation"
      ],
      "takeaway": "One-line core takeaway"
    }
  ]
}
Do NOT output markdown backticks or extra text outside the JSON.`
    );

    const response = await model.invoke([
        systemPrompt,
        new HumanMessage(prompt)
    ]);

    const rawContent = typeof response.content === 'string' ? response.content : JSON.stringify(response.content);

    let deckData = null;
    try {
        const jsonMatch = rawContent.match(/\{[\s\S]*\}/);
        if (jsonMatch) {
            deckData = JSON.parse(jsonMatch[0]);
        }
    } catch (parseErr) {
        console.warn('⚠️ JSON parse failed for slide deck, using fallback structure:', parseErr.message);
    }

    if (!deckData || !Array.isArray(deckData.slides)) {
        deckData = {
            deckTitle: "Executive Presentation",
            subtitle: prompt.slice(0, 60),
            slides: [
                {
                    slideTitle: "Strategic Overview",
                    bulletPoints: ["Initial assessment and market context", "Key opportunities identified", "Action plan"],
                    takeaway: "Strong growth potential"
                },
                {
                    slideTitle: "Execution Roadmap",
                    bulletPoints: ["Phase 1: Immediate deployment", "Phase 2: Scaling operations", "Phase 3: Optimization"],
                    takeaway: "Structured rollout plan"
                }
            ]
        };
    }

    // 2. Generate PPTX with PptxGenJS
    const pres = new PptxGenJS();
    pres.layout = 'LAYOUT_16x9';
    pres.author = 'Cortex AI Platform';
    pres.title = deckData.deckTitle;

    // Slide 1: Cover Slide
    const coverSlide = pres.addSlide();
    coverSlide.background = { color: '0F172A' }; // Dark slate/indigo
    coverSlide.addText(deckData.deckTitle, {
        x: '10%',
        y: '32%',
        w: '80%',
        fontSize: 36,
        color: 'FFFFFF',
        bold: true,
        align: 'center',
        fontFace: 'Arial'
    });
    coverSlide.addText(deckData.subtitle || 'Generated by Cortex AI', {
        x: '10%',
        y: '50%',
        w: '80%',
        fontSize: 18,
        color: '818CF8', // Indigo 400
        align: 'center',
        fontFace: 'Arial'
    });

    // Content Slides
    deckData.slides.forEach((s, idx) => {
        const slide = pres.addSlide();
        slide.background = { color: 'F8FAFC' };

        // Slide Header
        slide.addText(`${idx + 1}. ${s.slideTitle}`, {
            x: '5%',
            y: '8%',
            w: '90%',
            fontSize: 22,
            bold: true,
            color: '1E1B4B',
            fontFace: 'Arial'
        });

        // Bullets
        const bulletsText = (s.bulletPoints || []).map(b => ({
            text: b,
            options: { fontSize: 15, color: '334155', bullet: true, breakLine: true }
        }));

        slide.addText(bulletsText, {
            x: '7%',
            y: '22%',
            w: '86%',
            h: '50%',
            valign: 'top',
            lineSpacing: 26,
            fontFace: 'Arial'
        });

        // Bottom takeaway box
        if (s.takeaway) {
            slide.addText(`💡 Key Takeaway: ${s.takeaway}`, {
                x: '5%',
                y: '78%',
                w: '90%',
                fontSize: 12,
                color: '4338CA',
                bold: true,
                fontFace: 'Arial'
            });
        }
    });

    const pptBuffer = await pres.write({ outputType: 'nodebuffer' });
    const storageResult = await storeFileAndGetUrl(pptBuffer, `${deckData.deckTitle.slice(0, 20)}.pptx`, 'application/vnd.openxmlformats-officedocument.presentationml.presentation');

    const slidesSummary = deckData.slides.map((s, i) => `${i + 1}. **${s.slideTitle}**`).join('\n');

    return {
        response: `### 📊 ${deckData.deckTitle}\n\nI have generated a professional **${deckData.slides.length + 1}-slide PowerPoint presentation** (.pptx).\n\n**Slide Deck Overview:**\n${slidesSummary}\n\n👉 **[Download PowerPoint (.pptx)](${storageResult.url})**`,
        agent: 'ppt',
        images: [],
        url: storageResult.url,
        artifact: null
    };
};

export default runPptAgent;
