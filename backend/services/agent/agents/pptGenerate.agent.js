import PptxGenJS from 'pptxgenjs';
import { uploadToS3 } from '../utils/s3.js';

export const runPptGenerateAgent = async (prompt, title = 'Cortex AI Presentation') => {
    try {
        const pres = new PptxGenJS();
        pres.layout = 'LAYOUT_16x9';

        // Slide 1: Cover Slide
        const coverSlide = pres.addSlide();
        coverSlide.background = { color: '0F172A' };
        coverSlide.addText(title, {
            x: '10%',
            y: '35%',
            w: '80%',
            fontSize: 40,
            color: 'FFFFFF',
            bold: true,
            align: 'center'
        });
        coverSlide.addText("Generated by Cortex AI Multi-Agent Platform", {
            x: '10%',
            y: '55%',
            w: '80%',
            fontSize: 18,
            color: '94A3B8',
            align: 'center'
        });

        // Content Slides
        const sections = prompt.split('\n\n').filter(s => s.trim().length > 0);
        sections.forEach((sec, idx) => {
            const slide = pres.addSlide();
            slide.background = { color: 'F8FAFC' };

            // Header banner
            slide.addText(`Slide ${idx + 1}: Key Insights`, {
                x: '5%',
                y: '8%',
                w: '90%',
                fontSize: 24,
                bold: true,
                color: '1E293B'
            });

            // Body text
            slide.addText(sec, {
                x: '5%',
                y: '22%',
                w: '90%',
                h: '65%',
                fontSize: 16,
                color: '475569',
                lineSpacing: 24,
                valign: 'top'
            });
        });

        const pptBuffer = await pres.write({ outputType: 'nodebuffer' });
        const url = await uploadToS3(pptBuffer, 'presentation.pptx', 'application/vnd.openxmlformats-officedocument.presentationml.presentation');

        return {
            result: `I have generated your PowerPoint presentation (${sections.length + 1} slides). You can download it here:\n\n[Download Presentation](${url})`,
            type: 'ppt',
            url
        };
    } catch (error) {
        console.error('PPT Generation error:', error);
        throw error;
    }
};
