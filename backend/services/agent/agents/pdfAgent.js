import PDFDocument from 'pdfkit';
import { HumanMessage, SystemMessage } from "@langchain/core/messages";
import { getModel } from "../config/llmModels.js";
import { storeFileAndGetUrl } from "../utils/storageService.js";

/**
 * PDF Agent:
 * 1. LLM drafts comprehensive document content (title, executive summary, sections, conclusion).
 * 2. PDFKit compiles styled downloadable PDF.
 * 3. Saves via S3-ready storage abstraction and returns download URL.
 */
export const runPdfAgent = async (prompt, ragContext = '', ragSources = []) => {
    // 1. LLM drafts the document content
    const model = getModel('pdf');
    let systemText = `You are Cortex AI's Executive Document Author.
Given the user's request, draft a comprehensive, professional formal document or report.
Structure your output clearly with:
- TITLE: A clear, formal document title on the very first line starting with "TITLE: "
- EXECUTIVE SUMMARY: A paragraph summarizing the objective and core findings.
- SECTION 1, SECTION 2, etc.: Substantive, detailed analysis with bullet points and clear insights.
- CONCLUSION & RECOMMENDATIONS: Actionable next steps.

Write polished, ready-to-publish content.`;

    if (ragContext) {
        systemText += `\n\nKNOWLEDGE BASE CONTEXT (incorporate and reference these findings into the document analysis):\n${ragContext}`;
    }

    const draftSystemPrompt = new SystemMessage(systemText);

    const draftResponse = await model.invoke([
        draftSystemPrompt,
        new HumanMessage(prompt)
    ]);

    const draftedContent = typeof draftResponse.content === 'string'
        ? draftResponse.content
        : JSON.stringify(draftResponse.content);

    // Extract title
    const titleMatch = draftedContent.match(/^TITLE:\s*(.+)$/m);
    const documentTitle = titleMatch ? titleMatch[1].trim() : 'Cortex AI Document';
    const bodyContent = draftedContent.replace(/^TITLE:\s*.+$/m, '').trim();

    // 2. Generate PDF with PDFKit
    const pdfBuffer = await new Promise((resolve, reject) => {
        try {
            const doc = new PDFDocument({
                margin: 50,
                info: {
                    Title: documentTitle,
                    Author: 'Cortex AI Platform'
                }
            });

            const buffers = [];
            doc.on('data', chunk => buffers.push(chunk));
            doc.on('end', () => resolve(Buffer.concat(buffers)));

            // Header Banner
            doc.rect(0, 0, doc.page.width, 70).fill('#1e1b4b'); // Indigo 950
            doc.fontSize(20).fillColor('#ffffff').text(documentTitle, 50, 25, {
                width: doc.page.width - 100,
                align: 'left'
            });

            doc.moveDown(2);

            // Body Content
            const paragraphs = bodyContent.split('\n\n');
            let currentY = 95;

            for (const para of paragraphs) {
                const trimmed = para.trim();
                if (!trimmed) continue;

                // Check for headings (e.g. ### or SECTION or CAPITALIZED)
                if (trimmed.startsWith('#') || trimmed.startsWith('EXECUTIVE') || trimmed.startsWith('SECTION') || trimmed.startsWith('CONCLUSION')) {
                    const headingText = trimmed.replace(/^#+\s*/, '');
                    doc.fontSize(14).fillColor('#4338ca').text(headingText, 50, currentY, { bold: true });
                    currentY = doc.y + 8;
                } else {
                    doc.fontSize(10.5).fillColor('#334155').text(trimmed, 50, currentY, {
                        lineGap: 4,
                        paragraphGap: 8
                    });
                    currentY = doc.y + 8;
                }

                // Page overflow safeguard
                if (currentY > doc.page.height - 80) {
                    doc.addPage();
                    currentY = 50;
                }
            }

            // Footer
            doc.fontSize(9).fillColor('#94a3b8').text(
                `Generated by Cortex AI • ${new Date().toLocaleDateString()}`,
                50,
                doc.page.height - 40,
                { align: 'center' }
            );

            doc.end();
        } catch (err) {
            reject(err);
        }
    });

    // 3. Save via S3-ready storage abstraction
    const storageResult = await storeFileAndGetUrl(pdfBuffer, `${documentTitle.slice(0, 20)}.pdf`, 'application/pdf');

    let responseText = `### 📄 ${documentTitle}\n\nI have drafted and compiled your formal document into a downloadable PDF.\n\n**Executive Overview:**\n${bodyContent.slice(0, 300)}...\n\n👉 **[Download PDF Document](${storageResult.url})**`;

    if (ragSources && ragSources.length > 0) {
        const uniqueDocs = [...new Set(ragSources.map(s => s.docName))];
        responseText += `\n\n> 📄 **Cited Knowledge Documents:**\n` + uniqueDocs.map(d => `> - *${d}*`).join('\n');
    }

    return {
        response: responseText,
        agent: 'pdf',
        images: [],
        url: storageResult.url,
        artifact: null,
        ragSources: ragSources || []
    };
};

export default runPdfAgent;

